"""Create a clearly marked synthetic adapter example, not a Chromium observation."""
import asyncio
from dataclasses import replace
import json
from pathlib import Path
import sys
import tempfile

root = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(root),str(root / "tests")]
from test_collector_control import Browser
from study.collector import Collector, save
from study.config import Config
from study.queue import Queue
from study.export import export
from study.analysis import analyze


async def main():
    dest = root / "validation" / "adapter-example"
    dest.mkdir(parents=True,exist_ok=True)
    c = Config(profile="fixture",fixture_origins=["http://127.0.0.1:8123"],observation_seconds=0,domain_cooldown_seconds=0)
    with tempfile.TemporaryDirectory() as temp:
        q = Queue(temp)
        q.ingest([{"url":"http://127.0.0.1:8123/synthetic-legitimate","label":"legitimate","source":"adapter-simulation","confidence":"candidate"},
                  {"url":"http://127.0.0.1:8123/synthetic-phishing","label":"phishing","source":"adapter-simulation","confidence":"candidate"}])
        rid = q.start_run(c)
        for _ in range(2):
            item = q.claim(rid,c)
            record,events = await Collector(Browser(),c).observe(item)
            record["simulation_notice"] = "Adapter simulation only; not a browser capture or real site"
            artifact = save(q.root,record,events)
            q.finish(item,record["outcome"],record["eligible"],artifact,c)
            (dest / f"{item['label']}.record.json").write_text(json.dumps(record,indent=2))
            (dest / f"{item['label']}.events.jsonl").write_text("".join(json.dumps(event)+"\n" for event in events))
        q.finish_run(rid,"synthetic_example")
        export(q,dest,"parquet")
        export(q,dest,"csv")
        analyze(dest / "features.parquet",dest / "report",bootstrap=10)
    (dest / "README.md").write_text("# Synthetic adapter example\n\nThese two rows exercise serialization and analysis readiness. They were generated by a test adapter, not Chromium, and describe no real websites. They cannot support class comparisons or detection claims.\n")


asyncio.run(main())
